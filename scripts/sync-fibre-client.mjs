#!/usr/bin/env node

import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = (file) => readFile(new URL(file, root), 'utf8');
const networks = {};
for (const network of ['mainnet', 'mocha']) {
  networks[network] = JSON.parse(await read(`constants/${network}_versions.json`));
  for (const key of ['app-latest-tag', 'node-latest-tag']) {
    assert.match(networks[network][key], /^v\d+\.\d+\.\d+(?:-[\w.]+)?$/,
      `Invalid ${network} ${key}`);
  }
}

const briefPath = 'public/fibre-client.md';
const brief = await read(briefPath);
const start = '<!-- BEGIN GENERATED FIBRE CLIENT VERSIONS -->';
const end = '<!-- END GENERATED FIBRE CLIENT VERSIONS -->';
assert.equal(brief.split(start).length, 2, 'Expected one Fibre client version block');
assert.equal(brief.split(end).length, 2, 'Expected one Fibre client version block');
assert.ok(brief.indexOf(start) < brief.indexOf(end), 'Invalid Fibre client version markers');

const mainnet = networks.mainnet;
const mocha = networks.mocha;
const block = [
  start,
  `Valid for: celestia-app ${mainnet['app-latest-tag']} / ${mocha['app-latest-tag']}, celestia-node ${mainnet['node-latest-tag']} / ${mocha['node-latest-tag']}.`,
  '<!-- Generated by bun run generate:fibre-client from constants/mainnet_versions.json and constants/mocha_versions.json. -->',
  end,
].join('\n');
const updated = brief.slice(0, brief.indexOf(start)) + block
  + brief.slice(brief.indexOf(end) + end.length);
if (process.argv.includes('--check')) {
  assert.equal(brief, updated, 'Fibre client versions are stale. Run bun run generate:fibre-client.');
} else if (brief !== updated) {
  await writeFile(new URL(briefPath, root), updated);
}
console.log('Fibre client versions match the selected app and node tags.');
